export function ruTopics(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return `${count} тема`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) {
    return `${count} темы`;
  }
  return `${count} тем`;
}

export function ruOfTotal(shown: number, total: number): string {
  const mod10 = total % 10;
  const mod100 = total % 100;
  const word = mod10 === 1 && mod100 !== 11 ? "темы" : "тем";
  return `${shown} из ${total} ${word}`;
}
